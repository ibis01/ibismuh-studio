// S169 — the Universal Scene Schema (Programme B).
//
// The roadmap's ask: "a structured representation of each scene" that
// "must accommodate all six modes, validation, asset provenance and
// timeline synchronization". This module is that schema as code, sitting
// ON TOP of what the house already has — it does not replace the modes'
// documents (GraphicsDoc, the whiteboard doc, the rig doc, the Scene3D
// doc…); it ENVELOPES them:
//
//   UniversalScene = the Director-authored envelope (kind, clock,
//                    narration, provenance, S168 directives) + the mode's
//                    own document riding in `doc` (validated by THAT
//                    mode's validator at compile time — S170's job).
//
// Laws:
//   - STRICT validation with typed errors: this schema is machine-authored
//     data (the Director's output), not a client roundtrip cast — junk is
//     an ERROR, never silently coerced (the doc-parse tolerance law does
//     not apply here; fail-closed beats skip-and-render).
//   - PROVENANCE CLOSURE: every asset a scene references (background
//     assetId, narration assets) must exist in the scene's own assets[]
//     with its origin declared. A scene cannot point at an undeclared
//     asset — the provenance guarantee is structural, not conventional.
//   - DIRECTIVE LAW: the scene's directives pass the S168 batch gate
//     (assertNoInventedCommands) — a scene carrying an invented command
//     does not validate, full stop.
//   - TIMELINE SYNC: `projectUniversalScene` projects a scene onto the
//     S87 universal timeline's clip shape (kind mapping, clock, inbound
//     transition read from the scene's own boundary directive).
//
// Determinism: pure module — no Date, no Math.random, no I/O.

import { assertNoInventedCommands, type DirectorDirective } from "./director-vocabulary";
import type { TimelineClip } from "./timeline";

export const UNIVERSAL_SCENE_VERSION = 1;

// ---------------------------------------------------------------------------
// The six modes — the schema's closed kind set. These name the DIRECTOR's
// world (the six production modes); the composition timeline names its own
// track kinds (S87) and `projectUniversalScene` is the ONE mapping between
// the two vocabularies.
// ---------------------------------------------------------------------------

export const UNIVERSAL_SCENE_KINDS = [
  "graphics",
  "whiteboard",
  "slides",
  "classic",
  "character",
  "3d",
] as const;

export type UniversalSceneKind = (typeof UNIVERSAL_SCENE_KINDS)[number];

export const UNIVERSAL_ASSET_ORIGINS = ["native", "stock", "generated", "upload", "reuse"] as const;
export type UniversalAssetOrigin = (typeof UNIVERSAL_ASSET_ORIGINS)[number];

export const UNIVERSAL_ASSET_KINDS = ["image", "audio", "video", "font", "data"] as const;
export type UniversalAssetKind = (typeof UNIVERSAL_ASSET_KINDS)[number];

export const UNIVERSAL_PRODUCTION_MODES = ["free", "standard", "premium"] as const;
export type UniversalProductionMode = (typeof UNIVERSAL_PRODUCTION_MODES)[number];

// ---------------------------------------------------------------------------
// The walls — schema-level only (the engines keep their own finer walls;
// one writer each). The ceiling is the house engine wall (18 minutes at
// the 24 fps reference — SLIDES_KINETIC_FRAME_BUDGET 25_920 frames).
// ---------------------------------------------------------------------------

export const UNIVERSAL_SCENE_DURATION_MIN_MS = 250;
export const UNIVERSAL_SCENE_DURATION_MAX_MS = 1_080_000;

export interface UniversalAssetRef {
  readonly id: string;
  readonly kind: UniversalAssetKind;
  readonly origin: UniversalAssetOrigin;
  /** Content address when the asset has bytes (64-hex). */
  readonly sha256?: string;
  /** Licence hint — required for stock/generated by policy, optional here
   *  (the asset lane's validator owns the policy; the schema carries it). */
  readonly license?: string;
}

export interface UniversalSceneBackground {
  readonly type: "color" | "image" | "none";
  /** #rrggbb when type = "color". */
  readonly color?: string;
  /** Must resolve inside the scene's own assets[] (provenance closure). */
  readonly assetId?: string;
}

export interface UniversalSceneNarration {
  readonly text: string;
  /** The registry-resolved voice id (the Director suggests; the router
   *  disposes — S176). */
  readonly voiceId?: string;
  readonly providerHint?: string;
}

export interface UniversalScene {
  readonly version: typeof UNIVERSAL_SCENE_VERSION;
  /** Machine-facing id — slug-safe, unique within a project. */
  readonly sceneId: string;
  readonly kind: UniversalSceneKind;
  /** Integer milliseconds inside the schema walls. */
  readonly durationMs: number;
  /** Placement on the composition clock (seconds); absent ⇒ the compiler
   *  sequences scenes back-to-back. */
  readonly atSec?: number;
  readonly background?: UniversalSceneBackground;
  readonly narration?: UniversalSceneNarration;
  /** The provenance ledger — everything this scene references. */
  readonly assets: readonly UniversalAssetRef[];
  /** The S168 directives — the animation/camera/style layer. */
  readonly directives: readonly DirectorDirective[];
  /** The mode's own document (GraphicsDoc, the whiteboard doc, the rig
   *  doc, the Scene3D doc…). Opaque HERE — the mode's validator owns it
   *  (S170 compiles through the mode's own gate). */
  readonly doc?: Readonly<Record<string, unknown>>;
}

export interface UniversalSceneProject {
  readonly version: typeof UNIVERSAL_SCENE_VERSION;
  readonly title: string;
  readonly mode: UniversalProductionMode;
  readonly scenes: readonly UniversalScene[];
}

export interface UniversalSchemaError {
  readonly path: string;
  readonly code:
    | "version"
    | "kind"
    | "id"
    | "duration"
    | "clock"
    | "background"
    | "narration"
    | "assets"
    | "provenance-closure"
    | "directives"
    | "doc"
    | "mode"
    | "title";
  readonly message: string;
}

export type UniversalSceneVerdict =
  | { readonly ok: true; readonly scene: UniversalScene }
  | { readonly ok: false; readonly errors: readonly UniversalSchemaError[] };

// ---------------------------------------------------------------------------
// The validator — strict, returns EVERY failure (batch review beats
// whack-a-mole), never mutates, never coerces.
// ---------------------------------------------------------------------------

const SCENE_ID_RE = /^[a-z0-9][a-z0-9_-]{0,63}$/i;
const HEX_COLOR_RE = /^#[0-9a-f]{6}$/i;
const SHA256_RE = /^[0-9a-f]{64}$/i;

function err(path: string, code: UniversalSchemaError["code"], message: string): UniversalSchemaError {
  return { path, code, message };
}

/** Structural validation of ONE scene (the project-level uniqueness rules
 *  ride `validateUniversalProject`). */
export function validateUniversalScene(raw: unknown): UniversalSceneVerdict {
  const errors: UniversalSchemaError[] = [];
  const scene = raw as Partial<UniversalScene> | undefined;

  if (scene === undefined || typeof scene !== "object" || scene === null) {
    return { ok: false, errors: [err("$", "version", "the scene is not an object")] };
  }

  if (scene.version !== UNIVERSAL_SCENE_VERSION) {
    errors.push(err("$.version", "version", `expected ${UNIVERSAL_SCENE_VERSION}, got ${JSON.stringify(scene.version)}`));
  }
  if (typeof scene.sceneId !== "string" || !SCENE_ID_RE.test(scene.sceneId)) {
    errors.push(err("$.sceneId", "id", `"${String(scene.sceneId)}" is not a slug-safe scene id (letters/digits/_/- , ≤ 64 chars)`));
  }
  if (!(UNIVERSAL_SCENE_KINDS as readonly string[]).includes(String(scene.kind))) {
    errors.push(err("$.kind", "kind", `"${String(scene.kind)}" is not one of the six modes (${UNIVERSAL_SCENE_KINDS.join(", ")})`));
  }
  if (
    typeof scene.durationMs !== "number" ||
    !Number.isInteger(scene.durationMs) ||
    scene.durationMs < UNIVERSAL_SCENE_DURATION_MIN_MS ||
    scene.durationMs > UNIVERSAL_SCENE_DURATION_MAX_MS
  ) {
    errors.push(
      err(
        "$.durationMs",
        "duration",
        `durationMs must be an integer in [${UNIVERSAL_SCENE_DURATION_MIN_MS}, ${UNIVERSAL_SCENE_DURATION_MAX_MS}], got ${JSON.stringify(scene.durationMs)}`,
      ),
    );
  }
  if (scene.atSec !== undefined && (typeof scene.atSec !== "number" || !Number.isFinite(scene.atSec) || scene.atSec < 0)) {
    errors.push(err("$.atSec", "clock", "atSec must be a finite, non-negative number of seconds"));
  }

  // Background: typed; color must be #rrggbb; an image background must
  // resolve inside assets[] (the provenance closure).
  if (scene.background !== undefined) {
    const bg = scene.background as Partial<UniversalSceneBackground> | null;
    const bgType = bg?.type;
    if (bgType !== "color" && bgType !== "image" && bgType !== "none") {
      errors.push(err("$.background.type", "background", `"${String(bgType)}" is not a background type (color/image/none)`));
    } else if (bgType === "color") {
      if (typeof bg?.color !== "string" || !HEX_COLOR_RE.test(bg.color)) {
        errors.push(err("$.background.color", "background", `"${String(bg?.color)}" is not #rrggbb`));
      }
    } else if (bgType === "image") {
      if (typeof bg?.assetId !== "string" || bg.assetId.length === 0) {
        errors.push(err("$.background.assetId", "background", "an image background must name an asset"));
      }
    }
  }

  if (scene.narration !== undefined) {
    const n = scene.narration as Partial<UniversalSceneNarration> | null;
    if (typeof n?.text !== "string" || n.text.trim().length === 0) {
      errors.push(err("$.narration.text", "narration", "narration text must be a non-empty string"));
    }
    if (n?.voiceId !== undefined && (typeof n.voiceId !== "string" || n.voiceId.length === 0)) {
      errors.push(err("$.narration.voiceId", "narration", "voiceId must be a non-empty string when present"));
    }
  }

  // Assets: unique ids, closed kinds/origins, sha256 shape.
  const ids = new Set<string>();
  if (!Array.isArray(scene.assets)) {
    errors.push(err("$.assets", "assets", "assets must be an array (an empty one is fine)"));
  } else {
    for (const [i, a] of (scene.assets as readonly UniversalAssetRef[]).entries()) {
      const at = `$.assets[${i}]`;
      if (a === null || typeof a !== "object") {
        errors.push(err(at, "assets", "an asset ref must be an object"));
        continue;
      }
      if (typeof a.id !== "string" || a.id.length === 0) {
        errors.push(err(`${at}.id`, "assets", "an asset ref must carry a non-empty id"));
      } else if (ids.has(a.id)) {
        errors.push(err(`${at}.id`, "assets", `duplicate asset id "${a.id}"`));
      } else {
        ids.add(a.id);
      }
      if (!(UNIVERSAL_ASSET_KINDS as readonly string[]).includes(String(a.kind))) {
        errors.push(err(`${at}.kind`, "assets", `"${String(a.kind)}" is not an asset kind (${UNIVERSAL_ASSET_KINDS.join(", ")})`));
      }
      if (!(UNIVERSAL_ASSET_ORIGINS as readonly string[]).includes(String(a.origin))) {
        errors.push(err(`${at}.origin`, "assets", `"${String(a.origin)}" is not an asset origin (${UNIVERSAL_ASSET_ORIGINS.join(", ")})`));
      }
      if (a.sha256 !== undefined && (typeof a.sha256 !== "string" || !SHA256_RE.test(a.sha256))) {
        errors.push(err(`${at}.sha256`, "assets", "sha256 must be 64 hex characters when present"));
      }
    }
  }
  if (typeof (scene.background as UniversalSceneBackground | undefined)?.assetId === "string" && !ids.has((scene.background as UniversalSceneBackground).assetId as string)) {
    errors.push(err("$.background.assetId", "provenance-closure", `"${(scene.background as UniversalSceneBackground).assetId}" is not declared in the scene's assets[] — a scene cannot reference an undeclared asset`));
  }

  // Directives: the S168 batch gate, fail-closed.
  if (!Array.isArray(scene.directives)) {
    errors.push(err("$.directives", "directives", "directives must be an array (an empty one is fine — rest is the floor)"));
  } else {
    const gate = assertNoInventedCommands(scene.directives as readonly DirectorDirective[]);
    if (!gate.ok) {
      for (const [i, es] of gate.rejections) {
        for (const e of es) {
          errors.push(err(`$.directives[${i}]`, "directives", `${e.code}: ${e.message}`));
        }
      }
    }
  }

  if (scene.doc !== undefined && (typeof scene.doc !== "object" || scene.doc === null || Array.isArray(scene.doc))) {
    errors.push(err("$.doc", "doc", "doc must be an object when present (the mode's own document)"));
  }

  return errors.length === 0 ? { ok: true, scene: raw as UniversalScene } : { ok: false, errors };
}

/** Project-level validation: every scene structurally valid, sceneIds
 *  unique, mode closed, title honest. */
export function validateUniversalProject(raw: unknown): { ok: boolean; errors: readonly UniversalSchemaError[] } {
  const errors: UniversalSchemaError[] = [];
  const project = raw as Partial<UniversalSceneProject> | undefined;
  if (project === undefined || typeof project !== "object" || project === null) {
    return { ok: false, errors: [err("$", "version", "the project is not an object")] };
  }
  if (project.version !== UNIVERSAL_SCENE_VERSION) {
    errors.push(err("$.version", "version", `expected ${UNIVERSAL_SCENE_VERSION}`));
  }
  if (typeof project.title !== "string" || project.title.trim().length === 0) {
    errors.push(err("$.title", "title", "the project title must be a non-empty string"));
  }
  if (!(UNIVERSAL_PRODUCTION_MODES as readonly string[]).includes(String(project.mode))) {
    errors.push(err("$.mode", "mode", `"${String(project.mode)}" is not a production mode (${UNIVERSAL_PRODUCTION_MODES.join(", ")})`));
  }
  if (!Array.isArray(project.scenes) || project.scenes.length === 0) {
    errors.push(err("$.scenes", "kind", "a project needs at least one scene"));
    return { ok: false, errors };
  }
  const seen = new Set<string>();
  for (const [i, s] of (project.scenes as readonly unknown[]).entries()) {
    const verdict = validateUniversalScene(s);
    if (!verdict.ok) {
      for (const e of verdict.errors) errors.push({ ...e, path: `$.scenes[${i}]${e.path.slice(1)}` });
      continue;
    }
    const id = verdict.scene.sceneId;
    if (seen.has(id)) errors.push(err(`$.scenes[${i}].sceneId`, "id", `duplicate sceneId "${id}"`));
    seen.add(id);
  }
  return { ok: errors.length === 0, errors };
}

// ---------------------------------------------------------------------------
// Timeline synchronization — the ONE mapping from the Director's six-mode
// world onto the S87 universal timeline's track kinds. slides and classic
// scenes render through the video lane (their segments ride as video);
// the other four kinds project to their own track kind.
// ---------------------------------------------------------------------------

const KIND_TO_TRACK: Readonly<Record<UniversalSceneKind, TimelineClip["kind"]>> = {
  graphics: "graphics",
  whiteboard: "whiteboard",
  slides: "video",
  classic: "video",
  character: "character",
  "3d": "3d",
};

/** Project one scene onto the S87 clip shape. `sceneIndex` is 1-based
 *  (the clips reference scenes by index — the S2 doctrine). The inbound
 *  transition is read from `prevScene`'s directives (the boundary the
 *  previous scene leaves through). */
export function projectUniversalScene(
  scene: UniversalScene,
  sceneIndex: number,
  startSec: number,
  endSec: number,
  prevScene?: UniversalScene,
): TimelineClip {
  let transitionIn: string | null = null;
  if (prevScene !== undefined) {
    const boundary = `boundary:${sceneIndex - 1}`;
    const spec = prevScene.directives.find((d) => d.domain === "animation" && d.action.startsWith("transition:") && d.target === boundary);
    if (spec !== undefined) transitionIn = spec.action.slice("transition:".length);
  }
  const bg = scene.background;
  return {
    id: `s${sceneIndex}`,
    kind: KIND_TO_TRACK[scene.kind],
    sceneIndex,
    startSec,
    endSec,
    transitionIn,
    transitionOut: null,
    asset:
      bg?.type === "image" && typeof bg.assetId === "string"
        ? { source: "ai", stockSource: null, stockQuery: null }
        : null,
  };
}

/** The whole project's back-to-back projection (absent atSec ⇒ sequence);
 *  an explicit atSec wins (the sync hint). */
export function projectUniversalTimeline(project: UniversalSceneProject): TimelineClip[] {
  const clips: TimelineClip[] = [];
  let cursor = 0;
  let prev: UniversalScene | undefined;
  for (const [i, scene] of project.scenes.entries()) {
    const start = scene.atSec !== undefined ? scene.atSec : cursor;
    const end = start + scene.durationMs / 1000;
    clips.push(projectUniversalScene(scene, i + 1, start, end, prev));
    cursor = end;
    prev = scene;
  }
  return clips;
}

// ---------------------------------------------------------------------------
// JSON-stable serialization (sorted keys at every level — the house law).
// ---------------------------------------------------------------------------

/** Recursively key-sort a JSON value (directives, assets, docs alike). */
function sortValue(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortValue);
  if (v !== null && typeof v === "object") {
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(v as Record<string, unknown>).sort()) {
      out[key] = sortValue((v as Record<string, unknown>)[key]);
    }
    return out;
  }
  return v;
}

export function serializeUniversalScene(scene: UniversalScene): string {
  return JSON.stringify(sortValue(scene));
}

export function serializeUniversalProject(project: UniversalSceneProject): string {
  return JSON.stringify(sortValue(project));
}
